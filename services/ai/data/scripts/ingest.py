import json
import argparse
from pathlib import Path
from app.db import db
from app.embeddings import embed_texts

def ingest(reset=False):
    conn = db.get_connection()
    cur = conn.cursor()
    
    if reset:
        print("Resetting documents table...")
        cur.execute("TRUNCATE TABLE documents RESTART IDENTITY")
    
    data_dir = Path(__file__).parent.parent
    
    documents = []
    
    # 1. Ingest Products
    print("Reading products.json...")
    products_file = data_dir / "seed" / "products.json"
    if products_file.exists():
        with open(products_file, "r") as f:
            data = json.load(f)
            for product in data.get("products", []):
                # We need the product UUID here if possible, but seed has no UUIDs (they are generated by BE).
                # We'll rely on slug as reference. Wait, API contract says meta.product_id="<uuid|null>".
                # But since seed doesn't have UUIDs natively, we'll store slug in 'ref' and set product_id=None.
                content = f"Produk: {product['name']}\nKategori: {product['category_slug']}\nDeskripsi: {product['description']}\nMaterial: {', '.join(product['materials'])}\nDimensi: {product['dimensions']['width_cm']}x{product['dimensions']['depth_cm']}x{product['dimensions']['height_cm']} cm\nBerat: {product['weight_kg']} kg"
                documents.append({
                    "content": content,
                    "metadata": {
                        "type": "product",
                        "ref": product["slug"],
                        "product_id": None
                    }
                })
    
    # 2. Ingest Guides
    print("Reading guides...")
    guides_dir = data_dir / "kb" / "guides"
    if guides_dir.exists():
        for file in guides_dir.glob("*.md"):
            with open(file, "r") as f:
                content = f.read()
                documents.append({
                    "content": content,
                    "metadata": {
                        "type": "guide",
                        "ref": file.stem
                    }
                })
                
    # 3. Ingest FAQ
    print("Reading faq...")
    faq_file = data_dir / "kb" / "faq.md"
    if faq_file.exists():
        with open(faq_file, "r") as f:
            content = f.read()
            # simple chunking by Q&A pairs (splitting by H3)
            chunks = content.split("### ")
            for chunk in chunks[1:]:
                documents.append({
                    "content": "### " + chunk.strip(),
                    "metadata": {
                        "type": "faq",
                        "ref": "FAQ"
                    }
                })
                
    # 4. Ingest Policies
    print("Reading policies...")
    pol_file = data_dir / "kb" / "policies.md"
    if pol_file.exists():
        with open(pol_file, "r") as f:
            content = f.read()
            chunks = content.split("## ")
            for chunk in chunks[1:]:
                documents.append({
                    "content": "## " + chunk.strip(),
                    "metadata": {
                        "type": "policy",
                        "ref": "Kebijakan"
                    }
                })

    print(f"Total documents to ingest: {len(documents)}")
    
    # Batch embedding (max 100 per request for Gemini)
    batch_size = 100
    for i in range(0, len(documents), batch_size):
        batch = documents[i:i+batch_size]
        texts = [doc["content"] for doc in batch]
        print(f"Embedding batch {i//batch_size + 1}...")
        
        embeddings = embed_texts(texts)
        
        for doc, emb in zip(batch, embeddings):
            cur.execute(
                "INSERT INTO documents (content, metadata, embedding) VALUES (%s, %s, %s)",
                (doc["content"], json.dumps(doc["metadata"]), emb)
            )
            
    conn.commit()
    conn.close()
    print("Ingestion complete!")

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--reset", action="store_true")
    args = parser.parse_args()
    
    # Note: To run this, need to set PYTHONPATH or run as python -m data.scripts.ingest
    ingest(reset=args.reset)
